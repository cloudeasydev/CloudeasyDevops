export type InterviewQuestion = {
  id: string;
  text: string;
};

export type InterviewTopic = {
  id: string;
  title: string;
  short: string;
  questions: InterviewQuestion[];
};

function topic(id: string, title: string, short: string, questions: string[]): InterviewTopic {
  return {
    id,
    title,
    short,
    questions: questions.map((text, index) => ({
      id: `${id}-${String(index + 1).padStart(2, "0")}`,
      text,
    })),
  };
}

